"""Embed the uploaded mascot images into the plugin's client bundle.

The webserver serves plugin *bundles* under /plugins, not arbitrary files from a
package, so an <img src="..."> pointing next to client.js would 404. Embedding
the bytes as data URIs keeps the plugin self-contained and CSP-proof.

The generated constant is spliced between the `@dsd-artwork` markers in
client.js, so re-running this script after changing the images is enough.
"""

import base64
import re
from pathlib import Path

OBJECTS = Path.home() / ".dsh" / "attachments" / "v1" / "objects"
PACKAGE = Path(__file__).resolve().parent.parent / "dsh-deepseek-decor"
CLIENT = PACKAGE / "client.js"

START = "    // @dsd-artwork:start"
END = "    // @dsd-artwork:end"

# (key, sha256-prefixed object path, description shown in the generated file)
IMAGES = [
    ("chibi", "87/873e1c4870724a11f02fa08a2f97c2d0c7e004610093066b3135b548a8fe31df", "Q版坐姿"),
    ("portrait", "ac/ac9d521aeccb4a578e819a2af7c3a38425f0c29933fc35209bc4e554b02e51ac", "全身立绘"),
    ("meme", "0c/0c27c62b97553fb600bd199ff8b83f5b593f90341cb44f00775af0456189990b", "表情包"),
]


def mime_of(raw: bytes) -> str:
    if raw[:4] == b"RIFF" and raw[8:12] == b"WEBP":
        return "image/webp"
    if raw[:8] == b"\x89PNG\r\n\x1a\n":
        return "image/png"
    if raw[:3] == b"\xff\xd8\xff":
        return "image/jpeg"
    raise SystemExit("unsupported image format")


def build_block() -> str:
    lines = [
        START + " \u2014 generated by preview/embed_artwork.py, do not edit by hand",
        "/**",
        " * Data URIs for the mascot images the user supplied. They travel inside",
        " * the bundle because the webserver serves plugin bundles, not arbitrary",
        " * package files, so a sibling <img src> would 404.",
        " */",
        "const ARTWORK = {",
    ]
    for key, rel, description in IMAGES:
        raw = (OBJECTS / rel).read_bytes()
        payload = base64.b64encode(raw).decode("ascii")
        print(f"{key:9} {mime_of(raw):11} {len(raw):7} bytes -> {len(payload):7} chars  ({description})")
        lines.append(f"  /** {description} */")
        lines.append(f"  {key}:")
        lines.append(f"    'data:{mime_of(raw)};base64," + payload + "',")
    lines.append("};")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    source = CLIENT.read_text(encoding="utf-8")
    pattern = re.compile(
        re.escape(START) + r".*?" + re.escape(END),
        re.DOTALL,
    )
    if not pattern.search(source):
        raise SystemExit(f"markers {START!r} / {END!r} not found in {CLIENT}")

    block = build_block()
    updated = pattern.sub(lambda _m: block, source, count=1)
    CLIENT.write_text(updated, encoding="utf-8")
    print(f"\nspliced into {CLIENT} ({CLIENT.stat().st_size} bytes)")

    # The preview page loads the same pictures as plain files, so keep a copy
    # beside it; it cannot embed them without duplicating the base64 payload.
    shots = Path(__file__).resolve().parent / "art"
    shots.mkdir(exist_ok=True)
    for key, rel, _description in IMAGES:
        target = shots / f"{key}.webp"
        target.write_bytes((OBJECTS / rel).read_bytes())
    print(f"copied {len(IMAGES)} pictures to {shots}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
